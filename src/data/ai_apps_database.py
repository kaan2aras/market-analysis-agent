def get_all_apps():
    """Return all apps in the database."""
    return AI_APPS_DATABASE


def get_apps_by_category(category):
    """Filter apps by category."""
    return [app for app in AI_APPS_DATABASE if category.lower() in app["category"].lower()]


def get_apps_by_platform(platform):
    """
    Filter apps by platform availability.
    platform: 'ios', 'android', or 'both'
    """
    if platform.lower() == "ios":
        return [app for app in AI_APPS_DATABASE if app["app_store_link"]]
    elif platform.lower() == "android":
        return [app for app in AI_APPS_DATABASE if app["play_store_link"]]
    else:  # both
        return [app for app in AI_APPS_DATABASE if app["app_store_link"] and app["play_store_link"]]


def get_trending_apps(limit=20):
    """Get top trending apps sorted by trending score."""
    sorted_apps = sorted(AI_APPS_DATABASE, key=lambda x: x["trending_score"], reverse=True)
    return sorted_apps[:limit]


def get_apps_by_region(region):
    """Filter apps by region availability."""
    return [app for app in AI_APPS_DATABASE if region.lower() in app["region_availability"].lower()]
